  static final List<DiaryDefinition> predefinedDiariesAlphabetical = () {
    final list = List<DiaryDefinition>.from(predefinedDiaries);
    list.sort((a, b) => a.name.toLowerCase().compareTo(b.name.toLowerCase()));
    return List<DiaryDefinition>.unmodifiable(list);
  }();

  static DiaryDefinition? getDiaryById(String id) {
    try {
      return predefinedDiaries.firstWhere((d) => d.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<DiaryDefinition> getDiariesByCategory(DiaryCategoryType category) {
    return predefinedDiaries.where((d) => d.categoryType == category).toList();
  }

  static List<DiaryDefinition> getDiariesByCategoryId(String categoryId) {
    final cat = DiaryCategory.fromId(categoryId);
    return predefinedDiaries.where((d) => d.categoryType == cat.type).toList();
  }

  static List<DiaryDefinition> searchDiaries(String query, {DiaryCategoryType? categoryType}) {
    var list = predefinedDiaries;
    if (categoryType != null) {
      list = list.where((d) => d.categoryType == categoryType).toList();
    }
    if (query.trim().isEmpty) return list;
    return list.where((d) => d.matchesQuery(query)).toList();
  }
